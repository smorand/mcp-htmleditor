"""Build ``static/library.css`` from the design system (``make sync-library-design``).

Reads ``tokens.css`` and ``app.css`` of the design system (default ``~/projects/perso/app-design/assets/css``),
keeps the light and dark themes only (the library supports nothing else), drops every rule that names another
theme, removes the import rule, and appends ``tools/library-additions.css`` (what the library adds). The page
policy allows no external file, so the result is one self contained stylesheet.
Usage: ``sync_library_design.py [design css dir]``.
"""

from __future__ import annotations

import re
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "mcp_htmleditor" / "static" / "library.css"
ADDITIONS = ROOT / "tools" / "library-additions.css"
DEFAULT_SOURCE = Path.home() / "projects" / "perso" / "app-design" / "assets" / "css"
OTHER_THEME = re.compile(r'\[data-theme(?:\^|=)?=?"?(?:green|carbon)')
HEADER = """/* Web library pages (SPEC-0025). Generated by tools/sync_library_design.py from the design system
   ({source}) on {today}: light and dark themes only, the components of app.css, then tools/library-additions.css.
   The page policy allows no external file: no import rule, no font file (Inter and Fraunces fall back to the
   system fonts).
   Do not edit by hand: see .agent_docs/library-design.md. */
"""


def block(text: str, pattern: str) -> str:
    """The first CSS block of ``text`` matching ``pattern`` (a selector line to the closing brace at line start)."""
    found = re.search(pattern + r".*?\n\}", text, re.DOTALL)
    if found is None:
        raise SystemExit(f"tokens.css has no block {pattern!r}")
    return found.group(0)


def keep_rule(line: str) -> bool:
    """A line of app.css is dropped when it styles another theme than light or dark."""
    return OTHER_THEME.search(line) is None and "/* ===== Habillage Carbon" not in line


def build(source: Path) -> str:
    tokens = (source / "tokens.css").read_text(encoding="utf-8")
    components = (source / "app.css").read_text(encoding="utf-8").replace('@import url("tokens.css");\n', "")
    light = block(tokens, r':root,\[data-theme="light"\]\{')
    dark = block(tokens, r'\[data-theme="dark"\]\{')
    shared = block(tokens, r"\n:root\{\n")
    kept = "\n".join(line for line in components.splitlines() if keep_rule(line))
    head = HEADER.format(source=source, today=datetime.now(UTC).date())
    return f"{head}{light}\n{dark}{shared}\n{kept}\n{ADDITIONS.read_text(encoding='utf-8')}"


def main(arguments: list[str]) -> int:
    source = Path(arguments[0]) if arguments else DEFAULT_SOURCE
    OUTPUT.write_text(build(source), encoding="utf-8")
    sys.stdout.write(f"wrote {OUTPUT.relative_to(ROOT)} from {source}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
