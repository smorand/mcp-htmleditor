#!/usr/bin/env python3
"""Keep the shipped Breathe files consistent with the reference deck and the catalogue (SPEC-0023 DEC-015, DEC-016).

``templates/reference/slides/breathe.html`` is the single source of the Breathe layouts. This tool:

1. re-embeds the decoration of the reference deck and of the starting point from the catalogue
   (``templates/assets/breathe``), with the same code as ``mcp-htmleditor breathe-inline``;
2. writes ``LAYOUT_SETS.breathe`` in ``src/mcp_htmleditor/static/slide-layouts.js``, between
   ``/* breathe-layouts:begin */`` and ``/* breathe-layouts:end */``: one entry per reference slide, in order, labelled
   with its slide name, its ids written ``{{ID}}``, its page number ``{{N}}``, its named pictures emptied (the
   ``data-asset`` name is kept so a later ``breathe-inline`` fills them).

Usage:
    python tools/sync_breathe_layouts.py           # rewrite what is stale
    python tools/sync_breathe_layouts.py --check   # report freshness, write nothing, exit 1 when stale
"""

from __future__ import annotations

import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

from freshness import report_line
from mcp_htmleditor.breathe.inline import embed_assets

REPO = Path(__file__).resolve().parents[1]
REFERENCE = REPO / "templates" / "reference" / "slides" / "breathe.html"
BOOTSTRAP = REPO / "templates" / "bootstrap" / "slides-breathe-empty.html"
LAYOUTS_JS = REPO / "src" / "mcp_htmleditor" / "static" / "slide-layouts.js"
BEGIN = "/* breathe-layouts:begin */"
END = "/* breathe-layouts:end */"
ANCHOR = "/* ============================================================\n   Medical layouts"
MAKE_TARGET = "sync-breathe-layouts"
ARTICLE = re.compile(r"(?:<!--(?P<comment>(?:(?!-->).)*)-->\s*)?<article\s[^>]*data-type=\"slide\".*?</article>", re.S)
ICONS = {
    "title": "🎬",
    "disclosure": "⚖️",
    "agenda": "📋",
    "section": "📍",
    "keymessage": "🔢",
    "content": "📝",
    "table": "📊",
    "image": "🩻",
    "compare": "🆚",
    "steps": "🎯",
    "case": "🩺",
    "references": "📚",
    "thanks": "🙏",
}


def layouts(reference: str) -> list[dict[str, str]]:
    """One picker entry per slide of the reference deck, in order."""
    entries = []
    for match in ARTICLE.finditer(reference):
        article = match.group(0)[match.group(0).index("<article") :]
        title = re.search(r'data-title="([^"]*)"', article).group(1)  # type: ignore[union-attr]
        kind = re.search(r'data-slide-type="([^"]*)"', article).group(1)  # type: ignore[union-attr]
        comment = " ".join((match.group("comment") or title).split())
        comment = re.sub(r"^(?:LAYOUT|VARIANT) \w+ · ", "", comment)
        description = comment.split(": ", 1)[1] if ": " in comment else comment
        description = description[:1].upper() + description[1:]
        html = re.sub(r'(?<=\s)id="slide-\d+"', 'id="{{ID}}"', article, count=1)
        html = re.sub(r'data-id="slide-\d+"', 'data-id="{{ID}}"', html, count=1)
        html = re.sub(r'(<span class="slide-foot-page[^"]*">)\d+(</span>)', r"\g<1>{{N}}\g<2>", html)
        html = re.sub(r'(<img\b[^>]*\bdata-asset="[^"]*"[^>]*\ssrc=")[^"]*(")', r"\g<1>\g<2>", html)
        key = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
        entries.append(
            {"key": key, "label": title, "icon": ICONS.get(kind, "🫁"), "description": description, "html": html}
        )
    return entries


def layouts_block(reference: str) -> str:
    lines = [
        f"{BEGIN}",
        "/* Generated by tools/sync_breathe_layouts.py from templates/reference/slides/breathe.html (SPEC-0023):",
        "   edit the reference deck, then run make sync-breathe-layouts. */",
        "LAYOUT_SETS.breathe = {",
    ]
    for entry in layouts(reference):
        fields = ", ".join(
            f"{name}: {json.dumps(entry[name], ensure_ascii=False)}"
            for name in ("label", "icon", "description", "html")
        )
        lines.append(f"  {json.dumps(entry['key'])}: {{{fields}}},")
    lines += ["};", END]
    return "\n".join(lines)


def with_block(js: str, block: str) -> str:
    start = js.find(BEGIN)
    if start >= 0:
        end = js.index(END, start) + len(END)
        return js[:start] + block + js[end:]
    anchor = js.index(ANCHOR)
    return js[:anchor] + block + "\n\n" + js[anchor:]


def embedded(path: Path) -> str:
    """The text of ``path`` once its decoration is re-embedded from the catalogue (the file itself is untouched)."""
    with tempfile.TemporaryDirectory() as work:
        copy = Path(work) / path.name
        shutil.copyfile(path, copy)
        embed_assets(str(copy))
        return copy.read_text(encoding="utf-8")


def sync(check: bool) -> int:
    fresh = True
    targets: list[tuple[Path, str]] = [(path, embedded(path)) for path in (REFERENCE, BOOTSTRAP)]
    reference = targets[0][1]
    js = LAYOUTS_JS.read_text(encoding="utf-8")
    targets.append((LAYOUTS_JS, with_block(js, layouts_block(reference))))
    for path, expected in targets:
        current = path.read_text(encoding="utf-8")
        line, is_fresh = report_line(path.relative_to(REPO).as_posix(), expected, current, MAKE_TARGET)
        fresh &= is_fresh
        if check:
            print(line)
        elif not is_fresh:
            path.write_text(expected, encoding="utf-8")
            print(f"updated: {path.relative_to(REPO).as_posix()}")
        else:
            print(f"ok: {path.relative_to(REPO).as_posix()}")
    return 0 if fresh or not check else 1


if __name__ == "__main__":
    raise SystemExit(sync("--check" in sys.argv[1:]))
